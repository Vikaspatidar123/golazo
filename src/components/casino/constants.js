export function getProviderPath(systemId) {
  const provider = CASINO_PROVIDERS.find((p) => p.id === String(systemId));
  if (provider) return provider.path;

  const firstChar = String(systemId).charAt(0);
  switch (firstChar) {
    case "4":
      return "vivo";
    case "5":
      return "rrg";
    case "6":
      return "salsa";
    default:
      return "sg";
  }
}

